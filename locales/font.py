def decode_font(data, mapping=None):
    """Decode raw bytes (or a hexadecimal string), rejecting unmapped glyphs."""
    if isinstance(data, str):
        data = bytes.fromhex(data)
    mapping = FONT_MAP if mapping is None else mapping
    keys = sorted(
        ((bytes.fromhex(key), value) for key, value in mapping.items()),
        key=lambda item: -len(item[0]),
    )
    offset = 0
    output = []
    while offset < len(data):
        for key, char in keys:
            if data.startswith(key, offset):
                output.append(char)
                offset += len(key)
                break
        else:
            raise ValueError(
                f"Unmapped TI font bytes at offset {offset}: "
                f"{data[offset:].hex().upper()}"
            )
    return "".join(output)
